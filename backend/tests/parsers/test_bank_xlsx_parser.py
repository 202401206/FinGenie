"""Unit tests for bank statement XLSX parsing, worksheet selection, and security bounds."""

import io
import zipfile
from datetime import date
from decimal import Decimal
from uuid import UUID

import openpyxl
import pytest

from app.parsers.bank_statement import parse_bank_statement
from app.parsers.errors import (
    AmbiguousWorksheetError,
    InvalidStatementError,
    ResourceLimitError,
    UnsupportedFormatError,
)

DOC_ID = UUID("10000000-0000-4000-8000-000000000001")


def _create_synthetic_xlsx(
    *,
    sheet_name: str = "Account Statement",
    include_cover: bool = False,
    formula_in_amount: bool = False,
    include_ambiguous_sheet: bool = False,
) -> bytes:
    """Helper creating deterministic in-memory synthetic XLSX workbooks."""
    wb = openpyxl.Workbook()

    if include_cover:
        ws_cover = wb.active
        ws_cover.title = "Cover"
        ws_cover.append(["Bank Statement Export Summary"])
        ws_cover.append(["Generated by Synthetic Core Banking"])
        ws_data = wb.create_sheet(title=sheet_name)
    else:
        ws_data = wb.active
        ws_data.title = sheet_name

    # Preamble metadata rows (1 to 4)
    ws_data.append(["Bank: Synthetic Demo Bank"])
    ws_data.append(["Account Holder: Synthetic Person", "Account Type: savings"])
    ws_data.append(["Currency: INR", "Period: 2026-01-01 to 2026-01-31"])
    ws_data.append(["Opening Balance: 10000"])

    # Table Header (Row 5)
    ws_data.append(["Date", "Description", "Debit", "Credit", "Balance"])

    # Transactions (Rows 6 to 8)
    if formula_in_amount:
        ws_data.append(["2026-01-05", "Synthetic salary", 0, "=SUM(1000, 4000)", 15000])
    else:
        ws_data.append(["2026-01-05", "Synthetic salary", 0, 5000, 15000])

    ws_data.append(["2026-01-10", "Synthetic rent", 2000, 0, 13000])
    ws_data.append(["2026-01-15", "Synthetic groceries", 500, 0, 12500])

    # Footer (Row 9) and Unmapped (Row 10)
    ws_data.append(["Closing Balance: 12500"])
    ws_data.append(["Unrecognized export note", "Synthetic note only"])

    if include_ambiguous_sheet:
        ws_second = wb.create_sheet(title="Checking Account")
        ws_second.append(["Date", "Description", "Debit", "Credit", "Balance"])
        ws_second.append(["2026-01-01", "Opening", 0, 100, 100])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


class TestBankXLSXParser:
    """Verifies XLSX worksheet parsing, sheet selection, precision, and formula rejection."""

    def test_parse_standard_synthetic_xlsx(self) -> None:
        """Parses standard synthetic XLSX statement and checks full parity with bank-statement contract."""
        xlsx_bytes = _create_synthetic_xlsx(sheet_name="Account Statement")

        statement = parse_bank_statement(
            xlsx_bytes, file_kind="xlsx", document_id=DOC_ID
        )

        assert statement.bank == "Synthetic Demo Bank"
        assert statement.account_holder == "Synthetic Person"
        assert statement.account_type == "savings"
        assert statement.currency == "INR"
        assert statement.period_start == date(2026, 1, 1)
        assert statement.period_end == date(2026, 1, 31)
        assert statement.opening_balance == Decimal("10000")
        assert statement.closing_balance == Decimal("12500")

        # Source metadata must capture exact sheet title
        assert statement.source_metadata.document_id == DOC_ID
        assert statement.source_metadata.sheet_name == "Account Statement"

        # Source locations
        assert statement.source_locations["bank"].source_row == 1
        assert statement.source_locations["account_holder"].source_row == 2
        assert statement.source_locations["currency"].source_row == 3
        assert statement.source_locations["opening_balance"].source_row == 4
        assert statement.source_locations["closing_balance"].source_row == 9

        # Transactions
        assert len(statement.transactions) == 3
        t1, t2, t3 = statement.transactions

        assert t1.date == date(2026, 1, 5)
        assert t1.description == "Synthetic salary"
        assert t1.debit == Decimal("0")
        assert t1.credit == Decimal("5000")
        assert t1.balance == Decimal("15000")
        assert t1.source_row == 6

        assert t2.date == date(2026, 1, 10)
        assert t2.debit == Decimal("2000")
        assert t2.source_row == 7

        assert t3.date == date(2026, 1, 15)
        assert t3.debit == Decimal("500")
        assert t3.source_row == 8

        # Unmapped content
        assert len(statement.unmapped) == 1
        assert statement.unmapped[0].source_row == 10
        assert statement.unmapped[0].raw_label == "Unrecognized export note"
        assert statement.unmapped[0].raw_value == "Synthetic note only"

    def test_cover_sheet_ignored_and_matching_sheet_selected(self) -> None:
        """Ignores non-matching cover sheets and automatically selects the single data sheet."""
        xlsx_bytes = _create_synthetic_xlsx(
            sheet_name="Transactions", include_cover=True
        )

        statement = parse_bank_statement(
            xlsx_bytes, file_kind="xlsx", document_id=DOC_ID
        )
        assert statement.source_metadata.sheet_name == "Transactions"
        assert len(statement.transactions) == 3

    def test_ambiguous_sheets_rejected(self) -> None:
        """Workbooks with multiple candidate sheets matching table headers are rejected."""
        xlsx_bytes = _create_synthetic_xlsx(include_ambiguous_sheet=True)

        with pytest.raises(
            AmbiguousWorksheetError, match="multiple worksheets .* match"
        ):
            parse_bank_statement(xlsx_bytes, file_kind="xlsx", document_id=DOC_ID)

    def test_no_matching_sheet_rejected(self) -> None:
        """Workbooks with no matching table headers raise UnsupportedFormatError."""
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "EmptySheet"
        ws.append(["Random", "Columns", "Without", "Banking", "Headers"])
        buf = io.BytesIO()
        wb.save(buf)

        with pytest.raises(
            UnsupportedFormatError, match="No worksheet matches the supported"
        ):
            parse_bank_statement(buf.getvalue(), file_kind="xlsx", document_id=DOC_ID)

    def test_formula_in_financial_cells_rejected(self) -> None:
        """Formula cells in financial columns raise InvalidStatementError."""
        xlsx_bytes = _create_synthetic_xlsx(formula_in_amount=True)

        with pytest.raises(
            InvalidStatementError, match="Formulas are not supported in financial cells"
        ):
            parse_bank_statement(xlsx_bytes, file_kind="xlsx", document_id=DOC_ID)

    def test_native_excel_date_cells(self) -> None:
        """OpenPyXL native datetime/date cell values are extracted without string parsing errors."""
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "DatesTest"
        ws.append(["Date", "Description", "Debit", "Credit", "Balance"])
        ws.append([date(2026, 3, 1), "Native date test", 0, 100, 100])
        buf = io.BytesIO()
        wb.save(buf)

        statement = parse_bank_statement(
            buf.getvalue(), file_kind="xlsx", document_id=DOC_ID
        )
        assert len(statement.transactions) == 1
        assert statement.transactions[0].date == date(2026, 3, 1)

    def test_blank_movement_cells(self) -> None:
        """Empty debit or credit cells in XLSX evaluate to Decimal('0')."""
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Movements"
        ws.append(["Date", "Description", "Debit", "Credit", "Balance"])
        ws.append(["2026-01-01", "Deposit", None, 500, 500])
        ws.append(["2026-01-02", "Withdrawal", 200, None, 300])
        buf = io.BytesIO()
        wb.save(buf)

        statement = parse_bank_statement(
            buf.getvalue(), file_kind="xlsx", document_id=DOC_ID
        )
        assert statement.transactions[0].debit == Decimal("0")
        assert statement.transactions[0].credit == Decimal("500")
        assert statement.transactions[1].debit == Decimal("200")
        assert statement.transactions[1].credit == Decimal("0")


class TestBankXLSXSecurityContainer:
    """Verifies untrusted ZIP container checks, macro rejection, and archive limits."""

    def test_non_zip_bytes_rejected(self) -> None:
        """Arbitrary non-ZIP bytes are rejected as unsupported."""
        with pytest.raises(
            UnsupportedFormatError, match="File is not a valid XLSX workbook"
        ):
            parse_bank_statement(
                b"Not a zip file", file_kind="xlsx", document_id=DOC_ID
            )

    def test_macro_enabled_workbook_rejected(self) -> None:
        """Workbooks containing vbaProject.bin (.xlsm) are rejected."""
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as zf:
            zf.writestr("[Content_Types].xml", "<Types/>")
            zf.writestr("xl/workbook.xml", "<workbook/>")
            zf.writestr("xl/vbaProject.bin", b"fake macro binary payload")

        with pytest.raises(
            UnsupportedFormatError, match="Macro-enabled workbooks .* not supported"
        ):
            parse_bank_statement(buf.getvalue(), file_kind="xlsx", document_id=DOC_ID)

    def test_decompression_bomb_rejected(self) -> None:
        """Archives whose uncompressed entries exceed 25 MiB are rejected."""
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", "<Types/>")
            zf.writestr("xl/workbook.xml", "<workbook/>")
            # 26 MiB of zeros compresses to ~26 KB in memory
            zf.writestr("xl/worksheets/sheet1.xml", b"\x00" * (26 * 1024 * 1024))

        with pytest.raises(
            ResourceLimitError, match=r"Expanded XLSX content .* exceeds limit"
        ):
            parse_bank_statement(buf.getvalue(), file_kind="xlsx", document_id=DOC_ID)
